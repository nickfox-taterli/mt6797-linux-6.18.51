/*
 * MT6797 MSDC1 register map for the SD tuning path.
 *
 * The offsets and field positions below are hardware facts of the MT6797
 * MSDC block on this board; they are expressed here in the kernel's usual
 * register/field style.  The tuning engine only touches the registers this
 * board's MSDC1 SDR104 tuning needs; eMMC HS400 tuning lives in mtk-sd.c.
 */
#ifndef MT6797_SDAUTOK_REGS_H
#define MT6797_SDAUTOK_REGS_H

/* Register offsets from the MSDC base */
#define SDAUTOK_MSDC_CFG		0x000
#define SDAUTOK_MSDC_IOCON		0x004
#define SDAUTOK_MSDC_PS			0x008
#define SDAUTOK_MSDC_INT		0x00c
#define SDAUTOK_MSDC_INTEN		0x010
#define SDAUTOK_MSDC_FIFOCS		0x014
#define SDAUTOK_MSDC_RXDATA		0x01c
#define SDAUTOK_SDC_CMD			0x034
#define SDAUTOK_SDC_ARG			0x038
#define SDAUTOK_SDC_STS			0x03c
#define SDAUTOK_SDC_BLK_NUM		0x050
#define SDAUTOK_MSDC_PATCH_BIT0		0x0b0
#define SDAUTOK_MSDC_PATCH_BIT1		0x0b4
#define SDAUTOK_MSDC_PATCH_BIT2		0x0b8
#define SDAUTOK_MSDC_PAD_TUNE0		0x0f0
#define SDAUTOK_MSDC_PAD_TUNE1		0x0f4
#define SDAUTOK_EMMC50_CFG0		0x208
#define SDAUTOK_EMMC50_PAD_DS_TUNE	0x188

/* MSDC_CFG */
#define MSDC_CFG_CKPDN			BIT(1)
#define MSDC_CFG_RST			BIT(2)
#define MSDC_CFG_PIO			BIT(3)

/* MSDC_IOCON */
#define MSDC_IOCON_RSPL			BIT(1)
#define MSDC_IOCON_R_D_SMPL		BIT(2)
#define MSDC_IOCON_DDLSEL		BIT(3)
#define MSDC_IOCON_DDR50CKD		BIT(4)
#define MSDC_IOCON_R_D_SMPL_SEL		BIT(5)
#define MSDC_IOCON_W_D_SMPL_SEL		BIT(9)

/* MSDC_INT: W1C status bits */
#define MSDC_INT_CMDRDY			BIT(8)
#define MSDC_INT_CMDTMO			BIT(9)
#define MSDC_INT_RSPCRCERR		BIT(10)
#define MSDC_INT_XFER_COMPL		BIT(12)
#define MSDC_INT_DATTMO			BIT(14)
#define MSDC_INT_DATCRCERR		BIT(15)
#define MSDC_INT_CMD_DONE		(MSDC_INT_CMDRDY | MSDC_INT_CMDTMO | MSDC_INT_RSPCRCERR)
#define MSDC_INT_DATA_DONE		(MSDC_INT_XFER_COMPL | MSDC_INT_DATTMO | MSDC_INT_DATCRCERR)

/* MSDC_FIFOCS */
#define MSDC_FIFOCS_RXCNT		GENMASK(7, 0)
#define MSDC_FIFOCS_CLR			BIT(31)

/* SDC_STS */
#define SDC_STS_SDCBUSY			BIT(0)

/* MSDC_PS bit 16: DAT0 level during data-inhibit */
#define MSDC_PS_DAT0_INHIBIT		BIT(16)

/* MSDC_PATCH_BIT0 */
#define MSDC_PB0_RD_DAT_SEL		BIT(3)
#define MSDC_PB0_INT_DAT_LATCH_CK_SEL	GENMASK(9, 7)
#define MSDC_PB0_CKGEN_MSDC_DLY_SEL	GENMASK(14, 10)

/* MSDC_PATCH_BIT1 */
#define MSDC_PB1_WRDAT_CRCS_TA_CNTR	GENMASK(2, 0)
#define MSDC_PB1_CMD_RSP_TA_CNTR	GENMASK(5, 3)
#define MSDC_PB1_GET_BUSY_MA		BIT(6)
#define MSDC_PB1_GET_CRC_MA		BIT(7)

/* MSDC_PATCH_BIT2 */
#define MSDC_PB2_CFGRESP		BIT(15)
#define MSDC_PB2_RESPSTENSEL		GENMASK(18, 16)
#define MSDC_PB2_CFGCRCSTSEDGE		BIT(25)
#define MSDC_PB2_CFGCRCSTS		BIT(28)
#define MSDC_PB2_CRCSTSENSEL		GENMASK(31, 29)

/* MSDC_PAD_TUNE0 */
#define MSDC_PAD_TUNE0_DATRRDLY		GENMASK(12, 8)
#define MSDC_PAD_TUNE0_DATRRDLYSEL	BIT(13)
#define MSDC_PAD_TUNE0_RXDLYSEL		BIT(15)
#define MSDC_PAD_TUNE0_CMDRDLY		GENMASK(20, 16)
#define MSDC_PAD_TUNE0_CMDRRDLYSEL	BIT(21)
#define MSDC_PAD_TUNE0_CLKTXDLY		GENMASK(31, 27)

/* MSDC_PAD_TUNE1 */
#define MSDC_PAD_TUNE1_DATRRDLY2	GENMASK(12, 8)
#define MSDC_PAD_TUNE1_DATRRDLY2SEL	BIT(13)
#define MSDC_PAD_TUNE1_CMDRDLY2		GENMASK(20, 16)
#define MSDC_PAD_TUNE1_CMDRRDLY2SEL	BIT(21)

/* EMMC50_CFG0 (present on this MSDC block) */
#define MSDC_EMMC50_CFG_CRC_STS_EDGE	BIT(3)
#define MSDC_EMMC50_CFG_CRC_STS_SEL	BIT(4)
#define MSDC_EMMC50_CFG_CMD_RESP_SEL	BIT(9)

/* EMMC50_PAD_DS_TUNE */
#define MSDC_EMMC50_DS_DLYSEL		BIT(0)
#define MSDC_EMMC50_DS_DLY2SEL		BIT(1)
#define MSDC_EMMC50_DS_DLY1		GENMASK(6, 2)
#define MSDC_EMMC50_DS_DLY2		GENMASK(11, 7)
#define MSDC_EMMC50_DS_DLY3		GENMASK(16, 12)

#endif /* MT6797_SDAUTOK_REGS_H */
